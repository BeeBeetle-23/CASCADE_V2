"""Report built only from deterministic backend outputs. An LLM may never supply figures."""
import csv
import html
import io
from datetime import datetime, timezone
from sqlalchemy import select
from sqlalchemy.orm import Session
from app.db import models as m
from .engine import ADJ
from .state_store import current_claims, current_version, doc_node, load_engine

DISCLAIMER = ("Preliminary decision-support output generated by deterministic rules from synthetic or extracted evidence. "
              "It is not a credit decision. Discrepancies are not findings of fraud; they require human review.")
NOT_OK = {"unverified", "unsupported", "unavailable", "stale", "incomplete", "needs_review", "red", "amber"}
METRIC_INPUTS = {"m_dscr": ["c_cfads", "c_ds"], "m_cr": ["c_ca", "c_cl"]}
LIMITS = {"m_dscr": "Uses reported cash available for debt service, never total bank inflows. Unavailable if either input is missing or the denominator is zero.",
          "m_cr": "Uses reported current assets and liabilities; unavailable if either is missing or liabilities are zero."}


def _prov(c: m.Claim) -> dict:
    return dict(claim_id=c.id, claim_type=c.claim_type, value=str(c.value) if c.value is not None else None, unit=c.unit,
                document_id=c.source_document_id, document_version_id=c.document_version_id, page=c.page_number,
                excerpt=c.source_excerpt, extraction_mode=c.extraction_mode, verification=c.verification_status)


def build_report(db: Session, app: m.Application) -> dict:
    eng = load_engine(db, app); st = eng.state
    claims = {c.node_id: c for c in current_claims(db, app.id)}
    docs, integrity = [], []
    for d in db.scalars(select(m.Document).where(m.Document.application_id == app.id)):
        vs = list(db.scalars(select(m.DocumentVersion).where(m.DocumentVersion.document_id == d.id).order_by(m.DocumentVersion.version_number)))
        cur = current_version(db, d.id); node = doc_node(d)
        docs.append(dict(document_id=d.id, doc_type=d.doc_type, type_confirmed=d.type_confirmed, graph_node=node,
                         node_status=st[node]["status"] if node else None,
                         versions=[dict(version=v.version_number, filename=v.original_filename, sha256=v.file_hash, current=v.is_current,
                                        processing=v.processing_status, verification=v.verification_status, extraction_mode=v.extraction_mode,
                                        uploaded_at=v.uploaded_at.isoformat()) for v in vs]))
        for f in (cur.diagnostics if cur else []) or []:
            if f.get("level") in ("warning", "error") or f.get("code") == "pdf_metadata":
                integrity.append(dict(document_id=d.id, version=cur.version_number, **f))
    checks = []
    for node, det in eng.check_details().items():
        checks.append(dict(node=node, **det, evidence=[_prov(claims[c]) for c in det["compared"] if c in claims]))
    metrics = [dict(node=n, label=eng.g.nodes[n]["label"], value=st[n]["value"], status=st[n]["status"], reason=st[n]["reason"],
                    inputs=[dict(node=i, label=eng.g.nodes[i]["label"], value=st[i]["value"], status=st[i]["status"]) for i in ins],
                    limitations=LIMITS[n]) for n, ins in METRIC_INPUTS.items()]
    gaps = [dict(node=n, label=eng.g.nodes[n]["label"], type=eng.g.nodes[n]["type"], status=s["status"], reason=s["reason"])
            for n, s in st.items() if s["status"] in NOT_OK and eng.g.nodes[n]["type"] in ("document", "claim", "adjustment")]
    pending = [_prov(c) for c in claims.values() if c.verification_status != "verified"]
    audit = db.scalars(select(m.AuditEvent).where(m.AuditEvent.application_id == app.id).order_by(m.AuditEvent.id.desc()).limit(50)).all()
    rec = st["recommendation"]
    return dict(generated_at=datetime.now(timezone.utc).isoformat(), disclaimer=DISCLAIMER,
                application=dict(id=app.id, company=app.company_name, requested_amount=str(app.requested_amount), currency=app.currency,
                                 reporting_period=app.reporting_period, scenario=app.scenario_key),
                documents=docs, integrity_findings=integrity, consistency_and_reconciliation=checks, metrics=metrics,
                evidence_gaps=gaps, unverified_claims=pending,
                recommendation=dict(value=rec["value"], status=rec["status"], current=rec["status"] == "current", reasons=rec["reason"]),
                audit=[dict(id=e.id, ts=e.ts.isoformat(), type=e.event_type, actor=e.actor, target=e.target_entity, reason=e.reason,
                            affected=e.affected_node_ids, recommendation_before=e.recommendation_before, recommendation_after=e.recommendation_after)
                       for e in audit])


def report_csv(rep: dict) -> str:
    buf = io.StringIO(); w = csv.writer(buf); w.writerow(["section", "item", "status", "value", "detail"])
    for c in rep["consistency_and_reconciliation"]: w.writerow(["check", c["node"], c["status"], c["residual"] or c["reported_difference"], c["explanation"]])
    for mt in rep["metrics"]: w.writerow(["metric", mt["label"], mt["status"], mt["value"], mt["reason"]])
    for g in rep["evidence_gaps"]: w.writerow(["evidence_gap", g["label"], g["status"], "", g["reason"]])
    for i in rep["integrity_findings"]: w.writerow(["integrity", i["document_id"], i["level"], i["code"], i["message"]])
    r = rep["recommendation"]; w.writerow(["recommendation", "preliminary", r["status"], r["value"], r["reasons"]])
    return buf.getvalue()


def report_html(rep: dict) -> str:
    e = html.escape
    def rows(items, cols): return "".join("<tr>" + "".join(f"<td>{e(str(i.get(c) if i.get(c) is not None else '—'))}</td>" for c in cols) + "</tr>" for i in items) or f"<tr><td colspan={len(cols)}>None</td></tr>"
    def table(title, items, cols): return f"<h2>{e(title)}</h2><table><tr>{''.join(f'<th>{e(c)}</th>' for c in cols)}</tr>{rows(items, cols)}</table>"
    a, r = rep["application"], rep["recommendation"]
    docs = [dict(document=d["document_id"], type=d["doc_type"], status=d["node_status"], versions="; ".join(f"v{v['version']} {v['filename']} ({v['verification']})" for v in d["versions"])) for d in rep["documents"]]
    return f"""<!doctype html><html><head><meta charset=utf-8><title>Underwriting report - {e(a['company'])}</title><style>
body{{font:14px/1.5 system-ui,sans-serif;max-width:900px;margin:2rem auto;color:#1a1f2b}}h1{{margin-bottom:0}}h2{{margin-top:2rem;border-bottom:1px solid #d5d9e0}}
table{{border-collapse:collapse;width:100%}}th,td{{border:1px solid #d5d9e0;padding:4px 8px;text-align:left;vertical-align:top}}th{{background:#f3f4f7}}
.note{{background:#fff7e0;border:1px solid #e8c766;padding:8px 12px}}@media print{{body{{margin:0}}h2{{break-after:avoid}}tr{{break-inside:avoid}}}}</style></head><body>
<h1>Underwriting report — {e(a['company'])}</h1><p>{e(a['id'])} · requested {e(a['requested_amount'])} {e(a['currency'])} (lakh) · {e(a['reporting_period'])} · generated {e(rep['generated_at'])}</p>
<p class=note>{e(rep['disclaimer'])}</p>
<h2>Preliminary recommendation</h2><p><b>{e(str(r['value']))}</b> ({e(r['status'])}{'' if r['current'] else ' — not current: required evidence is invalid'})</p><p>{e(r['reasons'])}</p>
{table('Documents', docs, ['document','type','status','versions'])}
{table('Integrity findings', rep['integrity_findings'], ['document_id','level','code','message'])}
{table('Consistency and reconciliation', rep['consistency_and_reconciliation'], ['node','status','reported_difference','adjustments_total','residual','threshold','explanation'])}
{table('Financial metrics', rep['metrics'], ['label','status','value','reason','limitations'])}
{table('Missing, stale or unverified evidence', rep['evidence_gaps'], ['label','type','status','reason'])}
{table('Audit events (latest 50)', rep['audit'], ['id','ts','type','actor','target','reason','recommendation_before','recommendation_after'])}
</body></html>"""
